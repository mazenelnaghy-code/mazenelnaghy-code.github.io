/** Arabic counted nouns: 1 يوم, 2 يومان, 3–10 أيام, 11–99 يومًا, 100 يوم. */
export function arCount(n, one, two, few, many) {
  if (n === 1) return one;
  if (n === 2) return two;
  const r = n % 100;
  if (r >= 3 && r <= 10) return few;
  if (r >= 11) return many;
  return one;
}

